#!/usr/bin/env python3
"""Prepare one raw EuRoC ``mav0`` sequence for the monocular DROID demo.

The output deliberately uses the same generic session layout as a phone
capture.  This keeps evaluation data source agnostic:

    output/
      data -> <mav0>/cam0/data
      calib.txt
      frames.csv
      imu.csv
      imu_prior.csv
      cam0_sensor.yaml
      imu0_sensor.yaml

The camera image directory is a symbolic link by default, so preparing a
sequence does not duplicate EuRoC images.  ``imu_prior.csv`` is generated by
the production preintegration tool with the EuRoC camera--IMU extrinsic and
noise metadata from the two sensor YAML files.
"""

from __future__ import annotations

import argparse
import csv
import re
import shutil
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Sequence


TOOLS_DIR = Path(__file__).resolve().parent
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

from imu_preintegrate import build_imu_calibration, build_imu_prior


def _normalise_key(key: str) -> str:
    key = key.lstrip("\ufeff").lower()
    key = re.sub(r"\[[^\]]*\]", "", key)
    key = re.sub(r"[^a-z0-9]+", "_", key)
    return key.strip("_")


def _value(row: Dict[str, str], names: Sequence[str], default: str = "") -> str:
    wanted = {_normalise_key(name) for name in names}
    for key, value in row.items():
        if _normalise_key(key) in wanted and value not in (None, ""):
            return str(value)
    return default


def _timestamp_ns(row: Dict[str, str]) -> int:
    value = _value(row, ("timestamp_ns", "timestamp", "#timestamp [ns]"))
    if not value:
        raise ValueError(f"timestamp column is missing from row keys={list(row)}")
    stamp = float(value)
    return int(stamp if stamp > 1.0e12 else stamp * 1.0e9)


def _number(row: Dict[str, str], names: Sequence[str]) -> float:
    value = _value(row, names, "0")
    return float(value)


def _read_rows(path: Path) -> List[Dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _read_yaml_vector(path: Path, key: str) -> List[float]:
    text = path.read_text(encoding="utf-8")
    match = re.search(rf"^\s*{re.escape(key)}\s*:\s*\[([^\]]+)\]", text, re.M)
    if match is None:
        raise ValueError(f"cannot find {key} in {path}")
    return [float(value) for value in re.split(r"[,\s]+", match.group(1).strip()) if value]


def _replace_target(path: Path, force: bool) -> None:
    if not path.exists() and not path.is_symlink():
        return
    if not force:
        raise FileExistsError(f"output already exists: {path}; pass --force to replace it")
    if path.is_symlink() or path.is_file():
        path.unlink()
    else:
        shutil.rmtree(path)


def _write_frames(cam_csv: Path, output: Path) -> int:
    rows = _read_rows(cam_csv)
    prepared = []
    for row in rows:
        timestamp_ns = _timestamp_ns(row)
        filename = _value(row, ("filename",))
        if not filename:
            raise ValueError(f"filename column is missing from {cam_csv}")
        prepared.append((timestamp_ns, filename))

    prepared.sort(key=lambda item: item[0])
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=("frame_id", "timestamp_ns", "timestamp_sec", "filename"),
        )
        writer.writeheader()
        for frame_id, (timestamp_ns, filename) in enumerate(prepared):
            writer.writerow(
                {
                    "frame_id": frame_id,
                    "timestamp_ns": timestamp_ns,
                    "timestamp_sec": f"{timestamp_ns / 1.0e9:.9f}",
                    "filename": filename,
                }
            )
    return len(prepared)


def _write_imu(imu_csv: Path, output: Path) -> int:
    rows = _read_rows(imu_csv)
    prepared = []
    for row in rows:
        timestamp_ns = _timestamp_ns(row)
        prepared.append(
            {
                "timestamp_ns": timestamp_ns,
                "timestamp_sec": f"{timestamp_ns / 1.0e9:.9f}",
                "gx": _number(row, ("gx", "w_RS_S_x", "gyro_x")),
                "gy": _number(row, ("gy", "w_RS_S_y", "gyro_y")),
                "gz": _number(row, ("gz", "w_RS_S_z", "gyro_z")),
                "ax": _number(row, ("ax", "a_RS_S_x", "acc_x", "accel_x")),
                "ay": _number(row, ("ay", "a_RS_S_y", "acc_y", "accel_y")),
                "az": _number(row, ("az", "a_RS_S_z", "acc_z", "accel_z")),
            }
        )

    prepared.sort(key=lambda row: int(row["timestamp_ns"]))
    fields = ("timestamp_ns", "timestamp_sec", "gx", "gy", "gz", "ax", "ay", "az")
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(prepared)
    return len(prepared)


def _write_calibration(cam_yaml: Path, output: Path) -> None:
    intrinsics = _read_yaml_vector(cam_yaml, "intrinsics")
    if len(intrinsics) != 4:
        raise ValueError(f"EuRoC intrinsics must have four values: {cam_yaml}")
    try:
        distortion = _read_yaml_vector(cam_yaml, "distortion_coefficients")
    except ValueError:
        distortion = []
    values = intrinsics + distortion
    output.write_text(" ".join(f"{value:.12g}" for value in values) + "\n", encoding="utf-8")


def _validate_images(image_dir: Path, frames_csv: Path) -> None:
    with frames_csv.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise ValueError(f"no frames were written to {frames_csv}")
    for row in (rows[0], rows[-1]):
        path = image_dir / row["filename"]
        if not path.is_file():
            raise FileNotFoundError(f"EuRoC image referenced by frames.csv is missing: {path}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mav0", required=True, help="raw EuRoC mav0 directory")
    parser.add_argument("--output", required=True, help="prepared DROID input directory")
    parser.add_argument("--copy-images", action="store_true", help="copy cam0 images instead of creating data symlink")
    parser.add_argument("--force", action="store_true", help="replace existing generated files in output")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    mav0 = Path(args.mav0).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    cam_dir = mav0 / "cam0"
    imu_dir = mav0 / "imu0"
    image_dir = cam_dir / "data"
    cam_csv = cam_dir / "data.csv"
    imu_csv = imu_dir / "data.csv"
    cam_yaml = cam_dir / "sensor.yaml"
    imu_yaml = imu_dir / "sensor.yaml"

    for path in (image_dir, cam_csv, imu_csv, cam_yaml, imu_yaml):
        if not path.exists():
            raise FileNotFoundError(f"not a complete EuRoC mav0 directory: missing {path}")

    output.mkdir(parents=True, exist_ok=True)
    data_target = output / "data"
    _replace_target(data_target, args.force)
    if args.copy_images:
        shutil.copytree(image_dir, data_target)
    else:
        data_target.symlink_to(image_dir, target_is_directory=True)

    for source, name in ((cam_yaml, "cam0_sensor.yaml"), (imu_yaml, "imu0_sensor.yaml")):
        target = output / name
        _replace_target(target, args.force)
        shutil.copy2(source, target)

    frames_path = output / "frames.csv"
    imu_path = output / "imu.csv"
    calib_path = output / "calib.txt"
    prior_path = output / "imu_prior.csv"
    for path in (frames_path, imu_path, calib_path, prior_path):
        _replace_target(path, args.force)

    frame_count = _write_frames(cam_csv, frames_path)
    imu_count = _write_imu(imu_csv, imu_path)
    _write_calibration(cam_yaml, calib_path)
    _validate_images(data_target, frames_path)

    calibration = build_imu_calibration(
        cam_sensor_yaml=output / "cam0_sensor.yaml",
        imu_sensor_yaml=output / "imu0_sensor.yaml",
    )
    build_imu_prior(frames_path, imu_path, prior_path, calibration=calibration)

    (output / "source.txt").write_text(
        f"source_mav0={mav0}\n"
        f"image_data={image_dir}\n"
        f"groundtruth={mav0 / 'state_groundtruth_estimate0' / 'data.csv'}\n",
        encoding="utf-8",
    )
    print(f"prepared={output}")
    print(f"frames={frame_count}, imu_samples={imu_count}")
    print(f"calibration={calibration.source}")
    print(f"imu_prior={prior_path}")


if __name__ == "__main__":
    main()
